import pytest
from schola.core.protocols.protobuf.grpc_protocol import GrpcProtocol
from schola.scripts.common.settings import (
    EnvironmentSettings,
    UnrealExecutableSimulatorConfig,
)
from schola.scripts.sb3.train.settings import (
    Sb3CheckpointSettings,
    Sb3LoggingSettings,
    Sb3TrainingSettings,
    Sb3TrainScriptSettings,
)
from schola.scripts.sb3.train.train import main


@pytest.mark.skip(
    reason="Potentially, hangs if model does not learn sufficiently within the 30000 timesteps"
)
def test_train_basic(built_game_path):
    args = Sb3TrainScriptSettings(
        training_settings=Sb3TrainingSettings(timesteps=30000, disable_eval=False),
        logging_settings=Sb3LoggingSettings(enable_tensorboard=False),
        checkpoint_settings=Sb3CheckpointSettings(enable_checkpoints=False),
        environment_settings=EnvironmentSettings(
            simulator_settings=UnrealExecutableSimulatorConfig(
                executable_path=built_game_path,
                headless=True,
                map="/Game/Examples/Basic/Maps/BasicTrain",
                disable_script=True,
            )
        ),
    )
    print(args)
    mean, _ = main(args)
    assert (
        mean >= 0.05
    ), "Agent Does not path directly to either reward (Reward < 0.06)."
    assert (
        mean >= 0.95
    ), "Agent Does not path directly to the large reward (Reward < 0.96)."


def test_train_script_autogenerate_port(built_game_path):
    args = Sb3TrainScriptSettings(
        training_settings=Sb3TrainingSettings(timesteps=30000, disable_eval=True),
        logging_settings=Sb3LoggingSettings(enable_tensorboard=False),
        checkpoint_settings=Sb3CheckpointSettings(enable_checkpoints=False),
        environment_settings=EnvironmentSettings(
            simulator_settings=UnrealExecutableSimulatorConfig(
                executable_path=built_game_path,
                headless=True,
                map="/Game/Examples/Basic/Maps/BasicTrain",
            )
        ),
    )
    protocol = args.environment_settings.protocol_settings.make()
    protocol.start()
    try:
        assert isinstance(
            protocol, GrpcProtocol
        ), "Did not generate a gRPC protocol from args"

        assert (
            not protocol.tcp_socket is None
        ), f"Did not create a tcp_socket for autogenerated port {protocol.port}"
    finally:
        protocol.close()
